"""Write reports/verdicts.md from runs/*/result.json (numbers only from files, never typed by hand).

    python -m pilots.summarize
"""
import json
from pathlib import Path

from .verdict import verdict_pilotB

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"


def load(path):
    return json.loads(path.read_text()) if path.exists() else None


def pilot_a():
    lines = ["## Pilot A (EchoBase)", "",
             "| condition | meetings | split+merge+n:m share | W (95% CI) | R (95% CI) | floor | verdict |",
             "|---|---|---|---|---|---|---|"]
    for cond in ("structural", "asr"):
        r = load(RUNS / "pilotA" / cond / "s0" / "run" / "result.json")
        if not r:
            lines.append(f"| {cond} | not run | | | | | |")
            continue
        lines.append(f"| {cond} | {r['n_meetings']} | {r['share']:.3f} | {r['W']:.3f} "
                     f"[{r['W_ci95'][0]:.3f}, {r['W_ci95'][1]:.3f}] | {r['R']:.2f} "
                     f"[{r['R_ci95'][0]:.2f}, {r['R_ci95'][1]:.2f}] | {r['floor']:.4f} | **{r['verdict']}** |")
    lines += ["", "The verdict is taken on the structural condition. A PASS on R alone shows the baseline wastes "
              "recomputation on structural changes; it does not yet show EchoBase can avoid it safely.", ""]
    return lines


def pilot_b():
    res = {m: [load(RUNS / "pilotB" / m / f"s{s}" / "run" / "result.json") for s in (0, 1, 2)]
           for m in ("global", "lineage")}
    if not all(all(res[m]) for m in res):
        return ["## Pilot B (shared-error lineage)", "", "Not all six sampler runs are finished.", ""]
    budgets = sorted(int(n) for n in res["global"][0]["summary"])
    prec = {m: {n: [p for r in res[m] for p in r["trials"][str(n)]["prec"]] for n in budgets} for m in res}
    viol = {m: {n: sum(v for r in res[m] for v in r["trials"][str(n)]["viol"]) /
                sum(len(r["trials"][str(n)]["viol"]) for r in res[m]) for n in budgets} for m in res}
    n_meet = min(r["n_meetings"] for m in res for r in res[m])
    v = verdict_pilotB(prec, viol, n_meet)
    lines = ["## Pilot B (shared-error lineage)", "", "| labels n | global prec | global viol | lineage prec | lineage viol |",
             "|---|---|---|---|---|"]
    for n in budgets:
        mg, ml = (sum(prec[m][n]) / len(prec[m][n]) for m in ("global", "lineage"))
        lines.append(f"| {n} | {mg:.4f} | {viol['global'][n]:.3f} | {ml:.4f} | {viol['lineage'][n]:.3f} |")
    lines += ["", f"Meetings: {n_meet}. 300 trials per cell (3 seeds x 100). **Verdict: {v}**", ""]
    return lines


if __name__ == "__main__":
    out = ROOT / "reports" / "verdicts.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(["# Pilot verdicts (generated by pilots/summarize.py)", ""] + pilot_a() + pilot_b()) + "\n")
    print(out.read_text())
