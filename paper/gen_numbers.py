"""Write paper/numbers.tex: every number quoted in the paper text, as a LaTeX macro, read from reports/*.json.

    python paper/gen_numbers.py
No number in main.tex is typed by hand. A missing report leaves its macros undefined -> LaTeX shows \\missing{name}.
"""
