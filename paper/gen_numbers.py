"""Write paper/numbers.tex: every number quoted in the paper text, as a LaTeX macro, read from reports/*.json.

    python paper/gen_numbers.py
No number in main.tex is typed by hand. A missing report leaves its macros undefined -> LaTeX shows \\missing{name}.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REP = ROOT / "reports"
OUT = Path(__file__).with_name("numbers.tex")
macros = {}


def put(name, value, fmt="{:.3f}"):
    name = letters(name)
    macros[name] = fmt.format(value) if isinstance(value, float) else str(value)


def load(name):
    f = REP / name
    return json.loads(f.read_text()) if f.exists() else None


DIGITS = dict(zip("0123456789", ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]))


def letters(s):  # LaTeX macro names take letters only: digits are spelled out, the rest dropped
    return "".join(DIGITS.get(c, c) for c in s if c.isalnum())


conf = load("confirmatory.json")
if conf:
    for r in conf:
        h = r["id"]
        put(f"{h}med", r["median"]); put(f"{h}lo", r["ci_low"]); put(f"{h}hi", r["ci_high"])
        put(f"{h}pct", 100 * r["median"], "{:.0f}")  # the median as a percentage of the old value, for the abstract
        put(f"{h}valid", r["valid"]); put(f"{h}units", r["units"]); put(f"{h}guard", r["excluded_guard"])
        put(f"{h}T", r["T"], "{:.2f}"); put(f"{h}L", r["L"], "{:.2f}")
        p = r["sign_test_p"]
        put(f"{h}signp", "$<$0.001" if p < 0.001 else f"{p:.3f}")
        put(f"{h}above", sum(v is not None and v > r["T"] for v in r["per_unit"].values()))
        vals = [v for v in r["per_unit"].values() if v is not None]
        put(f"{h}min", min(vals)); put(f"{h}max", max(vals))

for tag, fname in (("", "explore_eval.json"), ("Mtwo", "explore_eval_model2.json"), ("Mthree", "explore_eval_model3.json"),
                   ("Ctx", "explore_eval_ctx.json"), ("Mphi", "explore_eval_phi.json"), ("Mseven", "explore_eval_7b.json")):
    ex = load(fname)
    if not ex:
        continue
    for w, qs in ex["ami"].items():
        for q, r in qs.items():
            if "median" in r:
                base = f"{w}{q.split('_')[0]}{tag}"
                put(base + "med", r["median"]); put(base + "lo", r["ci"][0]); put(base + "hi", r["ci"][1])
                put(base + "valid", r["valid"])
                if tag == "" and w == "W3" and q == "Q1":
                    put(base + "pct", 100 * r["median"], "{:.0f}")  # for the abstract
    for q, r in ex.get("wiki", {}).items():
        if "median" in r:
            base = f"Wiki{q.split('_')[0]}{tag}"
            put(base + "med", r["median"]); put(base + "lo", r["ci"][0]); put(base + "hi", r["ci"][1])
            put(base + "valid", r["valid"])
    d = ex.get("W2_minus_W1_Q1")
    if d:
        put(f"PlaceboGap{tag}med", d["median"]); put(f"PlaceboGap{tag}lo", d["ci"][0])
        put(f"PlaceboGap{tag}hi", d["ci"][1]); put(f"PlaceboGap{tag}larger", d["w2_larger"])

fl = load("explore_flips.json")
if fl:
    for w, r in fl.items():
        for c, v in r["flip_rate"].items():
            put(f"Flip{w}{c.replace('_', '')}", 100 * v, "{:.1f}")
        for b, tag in (("[0.8,1.25)", "same"), ("[0,0.5)", "half"), ("[2.0,inf)", "double")):
            v = r["by_length_ratio"].get(f"action_item/{b}")
            if v:
                put(f"Flip{w}{tag}", 100 * v["rate"], "{:.1f}")

thr = load("throughput.json")
if thr:
    rate = {(r["model"], r["version"]): r["calls_per_s"] for r in thr}
    put("ThrBig", rate[("Qwen2.5-1.5B", "manual")], "{:.0f}")
    put("ThrSmall", rate[("Qwen2.5-0.5B", "manual")], "{:.0f}")
    put("ThrMergeEight", rate[("Qwen2.5-1.5B", "merge8")], "{:.0f}")
    full_calls = next(r["calls"] for r in thr if r["model"] == "Qwen2.5-1.5B" and r["version"] == "manual")
    put("FullCalls", f"{full_calls:,}")
    put("FullMin", full_calls / rate[("Qwen2.5-1.5B", "manual")] / 60, "{:.0f}")
    e5 = load("e5_w1.json")
    if e5:  # minutes to maintain W1's changed cells per policy at the measured 1.5B rate on manual segments
        r_big = rate[("Qwen2.5-1.5B", "manual")]
        for key, tag in (("full", "Full"), ("hash", "Hash"), ("echobase@0.1", "Rules")):
            put(f"MaintMin{tag}", e5["policies"][key]["calls_mean"] / r_big / 60, "{:.1f}")

pw = REP / "power_sim.md"  # generated by echobase/power_sim.py: | H1 ... | n dev | median | CI | P(rule met) | ... |
if pw.exists():
    import re
    for line in pw.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\| (H\d) .*?\| \d+ \| ([\d.]+) \| .*? \| ([\d.]+) \|", line)
        if m:
            put(f"Power{m.group(1)}", float(m.group(3)), "{:.2f}")
            put(f"Dev{m.group(1)}med", float(m.group(2)))

for tag, model in (("", "Qwen2.5-1.5B-Instruct"), ("Mtwo", "Qwen2.5-0.5B-Instruct"), ("Mthree", "Qwen2.5-3B-Instruct"),
                   ("Ctx", "ctx"), ("Mphi", "Phi-3.5-mini-instruct"), ("Mseven", "Qwen2.5-7B-Instruct")):
    sg = load(f"explore_signed_{model}.json")  # D5: direction and absolute size
    if sg:
        for w, qs in sg["ami"].items():
            for q, r in qs.items():
                base = f"Sg{w}{q}{tag}"
                put(base + "up", r["up"]); put(base + "units", r["units"])
                put(base + "abs", 100 * r["abs"]["median"], "{:+.1f}")
                put(base + "abslo", 100 * r["abs"]["ci"][0], "{:+.1f}"); put(base + "abshi", 100 * r["abs"]["ci"][1], "{:+.1f}")
                put(base + "old", 100 * r["old_share_median"], "{:.1f}")
                if "absmag" in r:
                    put(base + "absmag", 100 * r["absmag"]["median"], "{:.1f}")
        for q, r in sg["wiki"].items():
            base = f"SgWiki{q}{tag}"
            put(base + "up", r["up"]); put(base + "units", r["units"])
            put(base + "abs", 100 * r["abs"]["median"], "{:+.1f}")
            put(base + "abslo", 100 * r["abs"]["ci"][0], "{:+.1f}"); put(base + "abshi", 100 * r["abs"]["ci"][1], "{:+.1f}")
            put(base + "old", 100 * r["old_share_median"], "{:.1f}")
            if "absmag" in r:
                put(base + "absmag", 100 * r["absmag"]["median"], "{:.1f}")
    gd = load(f"explore_gold_{model}.json")  # D5: agreement with AMI dialogue acts
    if gd:
        for col, s in gd["summary"].items():
            c = {"question": "Qu", "action_item": "Ac"}[col]
            put(f"Gold{c}{tag}share", 100 * s["gold_share_median"], "{:.1f}")
            for v, r in s.items():
                if isinstance(r, dict):
                    for k in ("share", "abs_err", "f1"):
                        put(f"Gold{c}{v}{k.replace('_', '')}{tag}", 100 * r[k] if k != "f1" else r[k],
                            "{:.1f}" if k != "f1" else "{:.2f}")

sc = load("explore_scale.json")  # D5 scale (second model, AMI meetings outside dev/eval)
sp = load("explore_scale_1.5b.json")  # D7 scale with the primary model
if sp:
    put("ScalePN", sp["meetings"])
    for w, qs in sp["pairs"].items():
        for q, r in qs.items():
            base = f"ScaleP{w}{q}"
            put(base + "med", r["median"]); put(base + "lo", r["ci"][0]); put(base + "hi", r["ci"][1])
            put(base + "up", r["up"]); put(base + "abs", 100 * r["abs_median"], "{:+.1f}")
    g = sp["W2_minus_W1_Q1"]
    put("ScalePGapmed", g["median"]); put("ScalePGaplo", g["ci"][0]); put("ScalePGaphi", g["ci"][1])
    put("ScalePGaplarger", g["w2_larger"])
if sc:
    put("ScaleN", sc["meetings"])
    for w, qs in sc["pairs"].items():
        for q, r in qs.items():
            base = f"Scale{w}{q}"
            put(base + "med", r["median"]); put(base + "lo", r["ci"][0]); put(base + "hi", r["ci"][1])
            put(base + "up", r["up"]); put(base + "down", r["down"])
            put(base + "abs", 100 * r["abs_median"], "{:+.1f}")
            n16 = r["nested"]["16"]
            put(base + "sixteenwidth", n16["ci"][1] - n16["ci"][0], "{:.2f}")
            put(base + "fullwidth", r["ci"][1] - r["ci"][0], "{:.2f}")
    g = sc["W2_minus_W1_Q1"]
    put("ScaleGapmed", g["median"]); put("ScaleGaplo", g["ci"][0]); put("ScaleGaphi", g["ci"][1])
    put("ScaleGaplarger", g["w2_larger"])
    put("ScaleCallsManual", f"{sc['calls']['manual']:,}")
    if thr:
        put("ScaleMinManual", sc["calls"]["manual"] / rate[("Qwen2.5-0.5B", "manual")] / 60, "{:.0f}")

cal = load("explore_calib.json")  # D6 calibration on fixed manual segments
if cal:
    names = {"model 1.5B->0.5B": "SwapHalf", "model 1.5B->3B": "SwapThree", "model 1.5B->Phi-3.5-mini": "SwapPhi",
             "model 1.5B->7B": "SwapSeven", "prompt 1.5B paraphrase": "Para",
             "prompt 1.5B paraphrase 2": "ParaB", "prompt 1.5B paraphrase 3": "ParaC", "prompt 1.5B paraphrase 4": "ParaD",
             "prompt 0.5B paraphrase": "ParaHalf", "context 1.5B (ctx, manual)": "Ctx"}
    for name, qs in cal["pairs"].items():
        for q, r in qs.items():
            if "median" in r:
                base = f"Cal{names[name]}{q}"
                put(base + "med", r["median"]); put(base + "lo", r["ci"][0]); put(base + "hi", r["ci"][1])
                put(base + "abs", 100 * r["abs_median"], "{:+.1f}")
cc = load("explore_ctxcost.json")
if cc:
    put("CtxRatio", sum(r["ratio"] * r["calls"] for r in cc.values()) / sum(r["calls"] for r in cc.values()), "{:.1f}")
    put("CtxTokPlain", cc["manual"]["plain_tokens_mean"], "{:.0f}"); put("CtxTokCtx", cc["manual"]["ctx_tokens_mean"], "{:.0f}")
fm = load("explore_formal.json")
if fm:
    for k, r in fm["monotonicity"].items():
        kk, col = k.split("/")
        c = {"action_item": "Ac", "question": "Qu"}[col]
        put(f"Mono{kk}{c}loss", 100 * r["loss_rate"], "{:.0f}"); put(f"Mono{kk}{c}emerge", 100 * r["emergence_rate"], "{:.0f}")
        put(f"Mono{kk}{c}n", f"{r['merged_segments']:,}")
    for col, r in fm["anchor_accuracy"].items():
        put(f"AnchorAcc{col.replace('_', '')}", 100 * r["accuracy"], "{:.0f}")
    pc = fm["power_curve"]
    if all("violation_rate" in r for r in pc.values()):
        put("PowerViolMax", max(r["violation_rate"] for r in pc.values()), "{:.4f}")
        put("PowerAlpha", next(iter(pc.values()))["alpha_per_stratum"], "{:.4f}")
        put("PowerStrata", next(iter(pc.values()))["strata"])
        put("PowerSampZero", 100 * pc["0.05/-0.05"]["sampled_share"], "{:.0f}")  # true error 0 at eps 0.05
        for eps in ("0.05", "0.10", "0.15"):
            at = pc[f"{eps}/+0.00"]
            below = pc[f"{eps}/-0.02"]
            e = round(float(eps) * 100)
            put(f"PowerCertAt{e}", 100 * at["certify_rate"], "{:.0f}"); put(f"PowerSampAt{e}", 100 * at["sampled_share"], "{:.0f}")
            put(f"PowerSampBelow{e}", 100 * below["sampled_share"], "{:.0f}")

pd3 = load("post_determinism_3b.json")
if pd3:
    put("DetThreeMism", sum(c["mismatch_budgets"] for c in pd3["columns"].values()))
    put("DetThreeN", next(iter(pd3["columns"].values()))["n"])

det = load("e0_determinism_eval.json")
if det:
    put("DetN", det["n"])
    put("DetMism", sum(v["label_mismatches"] for c in det["columns"].values() for v in c.values()))

for w in ("w1", "w3"):
    e5 = load(f"e5_{w}.json")
    if not e5:
        continue
    W = w.upper()
    put(f"E{W}cells", f"{e5['changed_cells']:,}"); put(f"E{W}tok", e5["mean_tokens_changed_segment"], "{:.1f}")
    for key, r in e5["policies"].items():
        pol, _, eps = key.partition("@")
        name = f"E{W}{pol}" + (f"eps{round(float(eps) * 100)}" if eps else "")
        put(name + "share", r["call_share"]); put(name + "err", r["cell_error_mean"], "{:.4f}")
        put(name + "viol", r["any_stratum_violation_rate"])
    put(f"E{W}hashcells", e5["rule_share"].get("hash", 0))
    put(f"E{W}hashpct", 100 * e5["rule_share"].get("hash", 0) / e5["changed_cells"], "{:.0f}")
    rules = e5["rules"]
    put(f"E{W}rulecells", f"{sum(r['n'] for r in rules.values()):,}")
    put(f"E{W}rulesn", len(rules))
    put(f"E{W}rulesmajority", sum(abs(r["rule_err"] - r["majority_err"]) < 1e-9 for r in rules.values()))
    if "entity_count/sum-union" in rules:
        put(f"E{W}sumunionkappa", rules["entity_count/sum-union"]["kappa"], "{:.2f}")
    put(f"E{W}advtrials", e5["trials"])
    put(f"E{W}advfammax", max(r["family_violation_rate"] for r in e5["adversarial"].values()))
    put(f"E{W}wall", e5["wall_clock_s"] / 60, "{:.0f}")
    runs = len(e5["policies"]) * (e5["trials"] + e5["boot"])  # policy x eps entries, each run over trials and resamples
    put(f"E{W}policyruns", f"{runs:,}")
    put(f"E{W}secperrun", e5["wall_clock_s"] / runs, "{:.2f}")  # upper bound: wall clock also covers the validity test
    for eps, r in e5["adversarial"].items():
        n = round(float(eps) * 100)
        put(f"E{W}adv{n}fam", r["family_violation_rate"]); put(f"E{W}adv{n}strata", r["strata_injected"])

cf = load("explore_confident.json")  # D7 drift over confident labels only
if cf:
    put("ConfMargin", cf["margin"], "{:.1f}")
    short = {"Qwen2.5-0.5B": "Half", "Qwen2.5-1.5B": "", "Qwen2.5-3B": "Three", "Qwen2.5-7B": "Seven",
             "Phi-3.5-mini": "Phi"}
    for label, rs in cf["models"].items():
        for k, r in rs.items():
            base = f"Conf{k.replace('/', '')}{short[label]}"
            put(base + "kept", 100 * r["kept_words_median"], "{:.0f}")
            if "median" in r["confident"]:
                c = r["confident"]
                put(base + "med", c["median"]); put(base + "lo", c["ci"][0]); put(base + "hi", c["ci"][1])
                put(base + "n", c["valid"])
for W in ("w1", "w3"):  # D7 pooled audit
    po = load(f"explore_pooled_{W}.json")
    if po:
        put(f"Pool{W.upper()}anchorerr", 100 * po["anchor_error"], "{:.0f}")
        put(f"Pool{W.upper()}anchored", f"{po['anchored_cells']:,}")
        put(f"Pool{W.upper()}certmax", max(r["certified_rate"] for r in po["eps"].values()), "{:.2f}")
        put(f"Pool{W.upper()}sharemax", max(r["call_share"] for r in po["eps"].values()))
        put(f"Pool{W.upper()}hash", po["hash_share"])
cz = load("explore_chunksize.json")  # D7 chunk window 120 -> 100 / 150
if cz:
    for name, r in cz.items():
        if name.startswith("120"):
            base = "Chunk" + name.split(">")[1]
            put(base + "med", r["median"]); put(base + "lo", r["ci"][0]); put(base + "hi", r["ci"][1])
            put(base + "abs", r["abs_median"], "{:+.1f}"); put(base + "up", r["up"])
            if "mean" in r:
                put(base + "mean", r["mean"]); put(base + "absmean", r["abs_mean"], "{:+.1f}")
                put(base + "changed", r["changed"])
tc = REP / "tables" / "cost.csv"  # cost table (paper/figs/cost.py)
if tc.exists():
    import csv
    rows = list(csv.DictReader(open(tc)))
    put("CostMinMin", min(float(r["gpu_min"]) for r in rows), "{:.0f}")
    put("CostMinMax", max(float(r["gpu_min"]) for r in rows), "{:.0f}")
    put("CostTokMax", max(int(r["tokens"]) for r in rows) / 1e6, "{:.1f}")
    put("CostCallsMax", f"{max(int(r['calls']) for r in rows):,}")
xh = load("post_crosshost_1.5b.json")  # D7 cross-host check of the primary model (gp231 vs gpulab2)
if xh:
    put("XhostPN", f"{xh['cells']:,}"); put("XhostPmism", xh["mismatches"])

lines = ["% generated by paper/gen_numbers.py from reports/*.json -- do not edit",
         r"\providecommand{\missing}[1]{\textbf{\textcolor{red}{??#1}}}"]
lines += [f"\\newcommand{{\\n{k}}}{{{v}}}" for k, v in sorted(macros.items())]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(macros)} macros -> {OUT.relative_to(ROOT)}")
