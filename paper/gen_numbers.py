macros = {}


def put(name, value, fmt="{:.3f}"):
    name = letters(name)
    macros[name] = fmt.format(value) if isinstance(value, float) else str(value)


def load(name):
    f = REP / name
    return json.loads(f.read_text()) if f.exists() else None


DIGITS = dict(zip("0123456789", ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]))


def letters(s):  # LaTeX macro names take letters only: digits are spelled out, the rest dropped
    return "".join(DIGITS.get(c, c) for c in s if c.isalnum())


