"""Tab. 5 (post-hoc, D5/D6): one row per scorer: relative drift D and absolute change of the primary queries, the
base share, and agreement with human labels. Rows whose reports are missing are left out.

    python paper/figs/models.py    # reads reports/explore_eval*.json, explore_signed_*.json, explore_gold_*.json
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REP = ROOT / "reports"
MODELS = [  # label, explore_eval file, model id basename (signed / gold files), family
    ("Qwen2.5-0.5B", "explore_eval_model2.json", "Qwen2.5-0.5B-Instruct"),
    ("Qwen2.5-1.5B (primary)", "explore_eval.json", "Qwen2.5-1.5B-Instruct"),
    ("Qwen2.5-3B", "explore_eval_model3.json", "Qwen2.5-3B-Instruct"),
    ("Qwen2.5-7B", "explore_eval_7b.json", "Qwen2.5-7B-Instruct"),
    ("Phi-3.5-mini (3.8B)", "explore_eval_phi.json", "Phi-3.5-mini-instruct"),
]


def load(name):
    f = REP / name
    return json.loads(f.read_text()) if f.exists() else None


def d(r):
    return f"{r['median']:.2f}" if r and "median" in r else "--"


def a(r):
    return f"{100 * r['absmag']['median']:.1f}" if r and "absmag" in r else "--"


rows = []
for label, ev, mid in MODELS:
    e, s, g = load(ev), load(f"explore_signed_{mid}.json"), load(f"explore_gold_{mid}.json")
    if not e:
        continue
    w1, w2, w4 = e["ami"]["W1"]["Q1"], e["ami"]["W2"]["Q1"], e["wiki"].get("Qd1")
    sw1 = s["ami"]["W1"]["Q1"] if s else None
    sw2 = s["ami"]["W2"]["Q1"] if s else None
    sw4 = s["wiki"].get("Qd1") if s else None
    base = f"{100 * sw1['old_share_median']:.1f}" if sw1 else "--"
    f1 = f"{g['summary']['question']['manual']['f1']:.2f}" if g else "--"
    rows.append(f"{label} & {base} & {d(w1)} & {a(sw1)} & {d(w2)} & {a(sw2)} & {d(w4)} & {a(sw4)} & {f1} \\\\")

tex = ["\\begin{tabular}{@{}lrrrrrrrr@{}}", "\\toprule",
       "& base & \\multicolumn{2}{c}{W1 diarizer$\\to$manual} & \\multicolumn{2}{c}{W2 placebo} & "
       "\\multicolumn{2}{c}{W4 chunker} & question \\\\",
       "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}",
       "scorer & share \\% & $D$ & $|\\Delta|$ pts & $D$ & $|\\Delta|$ pts & $D$ & $|\\Delta|$ pts & F1 \\\\", "\\midrule",
       *rows, "\\bottomrule", "\\end{tabular}"]
Path(__file__).with_name("models.tex").write_text("% generated by paper/figs/models.py\n" + "\n".join(tex) + "\n",
                                                   encoding="utf-8")
print("\n".join(tex))
