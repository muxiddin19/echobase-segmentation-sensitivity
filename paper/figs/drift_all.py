"""Tab. 2 (all queries x workloads x models) and Fig. 3 (dose-response over merge window k), from the exploratory reports.

    python paper/figs/drift_all.py   # reads reports/explore_eval.json, explore_eval_model2.json, confirmatory.json
                                     # writes paper/figs/drift_all.tex, reports/tables/drift_all.csv, paper/figs/granularity.pdf
"""
import csv
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[2]
REP = ROOT / "reports"
INK, GRAY, MUTED = "#1a1a1a", "#8c8c8c", "#b3b3b3"
models = {"1.5B": json.loads((REP / "explore_eval.json").read_text()),
          "0.5B": json.loads((REP / "explore_eval_model2.json").read_text()),
          "3B": json.loads((REP / "explore_eval_model3.json").read_text())}  # 3B: post-hoc (D5), W1/W2/W4 only
AMI_Q = [("Q1", "action item"), ("Q2", "question"), ("Q3", "neg.\\ sentiment"), ("Q4", "topic = cost"),
         ("Q5_entities", "entity sum"), ("Q6_topic_tvd", "topic distance")]
WIKI_Q = [("Qd1", "dated text"), ("Qd2_entities", "entity sum"), ("Qd3_topic_tvd", "topic distance")]
WL = ["W1", "W2", "W3"]


def cell(r):
    return "--" if not r or "median" not in r else f"{r['median']:.2f}"


rows, csv_rows = [], []
for q, label in AMI_Q:
    cells = []
    for w in WL:
        for mname, ex in models.items():
            if w == "W3" and mname == "3B":
                continue
            r = ex["ami"].get(w, {}).get(q)
            cells.append(cell(r))
            if r and "median" in r:
                csv_rows.append([w, q, mname, r["median"], *r["ci"], r["valid"]])
    rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
rows.append("\\midrule")
rows.append("\\multicolumn{9}{@{}l}{\\textit{W4, Wikipedia test (chunker change)}} \\\\")
for q, label in WIKI_Q:
    cells = []
    for mname, ex in models.items():
        r = ex["wiki"].get(q)
        cells.append(cell(r))
        if r and "median" in r:
            csv_rows.append(["W4", q, mname, r["median"], *r["ci"], r["valid"]])
    rows.append(f"{label} & \\multicolumn{{8}}{{l}}{{1.5B {cells[0]} \\quad 0.5B {cells[1]} \\quad 3B {cells[2]}}} \\\\")

tex = ["\\begin{tabular}{@{}lcccccccc@{}}", "\\toprule",
       "& \\multicolumn{3}{c}{W1 diarizer $\\to$ manual} & \\multicolumn{3}{c}{W2 placebo} & "
       "\\multicolumn{2}{c}{W3 speaker count} \\\\",
       "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-9}",
       "query & 1.5B & 0.5B & 3B & 1.5B & 0.5B & 3B & 1.5B & 0.5B \\\\", "\\midrule", *rows, "\\bottomrule",
       "\\end{tabular}"]
Path(__file__).with_name("drift_all.tex").write_text("% generated by paper/figs/drift_all.py\n" + "\n".join(tex) + "\n",
                                                      encoding="utf-8")
(REP / "tables").mkdir(exist_ok=True)
with open(REP / "tables" / "drift_all.csv", "w", newline="") as fh:
    wr = csv.writer(fh)
    wr.writerow(["workload", "query", "model", "median", "ci_lo", "ci_hi", "valid"])
    wr.writerows(csv_rows)

# Fig. 3: Q1 drift vs merge window k (granularity), with the placebo (k = 1, boundaries moved) as reference
ex = models["1.5B"]["ami"]
pts = [(k, ex[f"E6_k{k}"]["Q1"]) for k in (2, 4, 8)]
plac = ex["W2"]["Q1"]
plt.rcParams.update({"font.family": "serif", "font.size": 8, "axes.linewidth": 0.6})
fig, ax = plt.subplots(figsize=(3.4, 1.9))
xs = [k for k, _ in pts]
ax.plot(xs, [r["median"] for _, r in pts], color=INK, lw=1.4, zorder=2)
for k, r in pts:
    ax.plot([k, k], r["ci"], color=INK, lw=1.4, solid_capstyle="round")
    ax.plot(k, r["median"], "o", color=INK, ms=4.5, mec="white", mew=0.8, zorder=3)
    ax.text(k * 1.07, r["median"], f"{r['median']:.2f}", va="center", fontsize=7)
ax.axhspan(*plac["ci"], color="#efefef", zorder=0, lw=0)  # placebo: same sizes, boundaries moved (not a k)
ax.axhline(plac["median"], color=GRAY, lw=1.0, ls="--", zorder=1)
ax.text(5.0, plac["median"] + 0.015, f"placebo {plac['median']:.2f}", va="bottom",
        fontsize=6.5, color=GRAY)
ax.set_xscale("log", base=2)
ax.set_xticks([2, 4, 8])
ax.set_xticklabels(["2", "4", "8"])
ax.set_xlim(1.6, 12)
ax.set_ylim(0, None)
ax.set_xlabel("merge window k (same-speaker segments merged)")
ax.set_ylabel("drift D of Q1")
ax.grid(axis="y", color="#e6e6e6", lw=0.5)
ax.set_axisbelow(True)
for s in ("top", "right"):
    ax.spines[s].set_visible(False)
fig.tight_layout(pad=0.3)
fig.savefig(Path(__file__).with_name("granularity.pdf"), bbox_inches="tight", pad_inches=0.02)
fig.savefig(Path(__file__).with_name("granularity.png"), dpi=200, bbox_inches="tight", pad_inches=0.02)
print("\n".join(tex))
