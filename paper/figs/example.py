"""Fig. 1: a real AMI eval excerpt where the same words get different action_item labels under the two segmentations.

    PYTHONPATH=. python paper/figs/example.py      # on the server (needs AMI annotations, outputs/diar and the v2 caches)
Picks, deterministically, the shortest manual segment whose action_item label differs from every diarizer segment
whose words are exactly the union of 2+ diarizer segments (8-30 words), and writes paper/figs/example.tex (a tabular).
"""
import json
from pathlib import Path

from pilots.ami import meetings

from echobase.lineage import provenance, versions

ROOT = Path(__file__).resolve().parents[2]
V2 = ROOT / "outputs" / "echobase" / "v2"


def tex(s):
    for a, b in (("\\", ""), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_")):
        s = s.replace(a, b)
    return s


best = None
for m in meetings("eval"):
    old, new, _ = versions(m)
    ov = json.loads((V2 / "w1old" / "action_item" / f"{m}.json").read_text())["values"]
    nv = json.loads((V2 / "manual" / "action_item" / f"{m}.json").read_text())["values"]
    prov = provenance(old, new)
    for j, seg in enumerate(new.segs):
        c = prov[j]["contrib"]
        if len(c) < 2 or not prov[j]["exact_union"] or any(ov[i] == nv[j] for i in c):
            continue
        n_old = sum(len(old.segs[i].text.split()) for i in c)
        if not 8 <= n_old <= 30:
            continue
        key = (n_old, m, j)
        if best is None or key < best[0]:
            best = (key, m, [(old.segs[i].speaker, old.segs[i].text, ov[i]) for i in c],
                    (seg.speaker, seg.text, nv[j]))

(_, m, olds, (spk, text, val)) = best
rows = ["\\begin{tabular}{@{}p{0.70\\columnwidth}l@{}}", "\\toprule",
        "\\textbf{Diarizer turns (W1 old)} & \\textbf{action item} \\\\", "\\midrule"]
rows += [f"{tex(t)} & {v} \\\\" for _, t, v in olds]
rows += ["\\midrule", "\\textbf{Manual segment (W1 new)} & \\\\", "\\midrule", f"{tex(text)} & {val} \\\\",
         "\\bottomrule", "\\end{tabular}"]
out = Path(__file__).with_name("example.tex")
out.write_text(f"% generated by paper/figs/example.py: meeting {m}\n" + "\n".join(rows) + "\n", encoding="utf-8")
print(m, olds, (spk, text, val))
