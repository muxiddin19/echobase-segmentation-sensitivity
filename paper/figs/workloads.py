"""Tab. 1: per workload, units, mean segments per unit (old / new), change share and Q(old) coverage (held-out data).

    PYTHONPATH=. python paper/figs/workloads.py     # on the server; writes paper/figs/workloads.tex and reports/tables/workloads.csv
Change share = share of new segments whose text is not identical to an old segment (pilots.segmap.change_map).
Coverage = units whose primary-query answer on the old side is >= 0.02 (the drift guard).
"""
import csv
import json
from pathlib import Path

import numpy as np

from pilots.ami import meetings
from pilots.segmap import change_map

from echobase import drift
from echobase.lineage import system_version, versions
from echobase.score_versions import W3_OLD, build
from echobase.wiki import articles

ROOT = Path(__file__).resolve().parents[2]
V2 = ROOT / "outputs" / "echobase" / "v2"

AMI = [("W1", "diarizer → manual", "w1old", "manual"), ("W2", "manual → placebo", "manual", "placebo"),
       ("W3", "est. → known count", "w3old", "w1old"), ("E6", "manual → merge k=4", "manual", "merge4")]


def segs(version, m):
    if version == "w3old":
        return system_version(m, W3_OLD / f"{m}.json", "w3o")[0].segs
    return build(version, m).segs


rows = []
for wid, desc, old, new in AMI:
    if not (V2 / new / "action_item").exists():
        continue
    n_old, n_new, changed, cov = [], [], [], 0
    for m in meetings("eval"):
        so, sn = segs(old, m), segs(new, m)
        n_old.append(len(so)); n_new.append(len(sn))
        km = {j: k for k, _, n in change_map(so, sn) for j in n}
        changed.append(sum(km.get(j, "new") != "unchanged" for j in range(len(sn))) / len(sn))
        v, l = drift.ami_load(old, "action_item", m)
        cov += drift.share(v, l, "yes") >= drift.GUARD
    rows.append((wid, desc, "AMI eval", len(n_old), np.mean(n_old), np.mean(n_new), np.mean(changed), cov))

n_old, n_new, changed, cov = [], [], [], 0
for a in articles("test"):
    f = {ch: json.loads((V2 / "wiki" / ch / "doc_date" / f"{a['id']}.json").read_text()) for ch in ("fixed", "para")}
    so = [tuple(s) for s in f["fixed"]["spans"]]
    sn = [tuple(s) for s in f["para"]["spans"]]
    n_old.append(len(so)); n_new.append(len(sn))
    changed.append(sum(s not in set(so) for s in sn) / len(sn))
    cov += drift.share(f["fixed"]["values"], [e - s for s, e in so], "yes") >= drift.GUARD
rows.append(("W4", "windows → paragraphs", "Wikipedia test", len(n_old), np.mean(n_old), np.mean(n_new),
             np.mean(changed), cov))

out = ROOT / "reports" / "tables"
out.mkdir(parents=True, exist_ok=True)
with open(out / "workloads.csv", "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["workload", "change", "data", "units", "segments_old", "segments_new", "change_share", "covered_units"])
    w.writerows(rows)
tex = ["\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule",
       "& change & units & seg.\\ old & new & changed & cov. \\\\", "\\midrule"]
ARROW = "$\\to$"
tex += [f"{r[0]} & {r[1].replace('→', ARROW)} & {r[3]} & {r[4]:.0f} & {r[5]:.0f} & {r[6]:.2f} & {r[7]} \\\\"
        for r in rows]
tex += ["\\bottomrule", "\\end{tabular}"]
Path(__file__).with_name("workloads.tex").write_text("% generated by paper/figs/workloads.py\n" + "\n".join(tex) + "\n",
                                                      encoding="utf-8")
for r in rows:
    print(r)
