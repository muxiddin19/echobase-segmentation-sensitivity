"""Tab. 3: maintenance policies on AMI eval (E5): LLM call share vs full recompute and true cell error, per eps.

    python paper/figs/maintenance.py     # reads reports/e5_w1.json (and e5_w3.json if present); writes
                                         # paper/figs/maintenance.tex and reports/tables/maintenance.csv
Cells: call share with its 95% meeting-bootstrap interval (the whole policy re-run in each resample) and the mean true
cell error in percent, over 100 trials.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EPS = ("0.02", "0.05", "0.1", "0.15")
NAMES = {"hash": "content hash (exact)", "anchor_cert": "anchor + audit", "echobase": "rules/anchor + audit",
         "echobase_conf": "\\quad + confidence strata"}

rows, csv_rows = [], []
for w in ("w1", "w3"):
    f = ROOT / "reports" / f"e5_{w}.json"
    if not f.exists():
        continue
    r = json.loads(f.read_text())
    pol = r["policies"]
    rows.append(f"\\multicolumn{{{1 + 2 * len(EPS)}}}{{@{{}}l}}{{\\textit{{{w.upper()}: {r['changed_cells']:,} changed cells}}}} \\\\")
    for p, label in NAMES.items():
        cells = []
        for e in EPS:
            x = pol[p] if p == "hash" else pol[f"{p}@{e}"]
            lo, hi = x["call_share_ci"]
            cells.append(f"{x['call_share']:.3f} [{lo:.2f}, {hi:.2f}] & {100 * x['cell_error_mean']:.2f}")
            csv_rows.append([w, p, e, x["call_share"], lo, hi, x["cell_error_mean"], *x["cell_error_ci"],
                             x["any_stratum_violation_rate"]])
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    rows.append("\\midrule")
rows = rows[:-1]

out = ROOT / "reports" / "tables"
out.mkdir(parents=True, exist_ok=True)
with open(out / "maintenance.csv", "w", newline="") as fh:
    wr = csv.writer(fh)
    wr.writerow(["workload", "policy", "eps", "call_share", "share_lo", "share_hi", "cell_error", "err_lo", "err_hi",
                 "any_violation_rate"])
    wr.writerows(csv_rows)
head = " & ".join(f"\\multicolumn{{2}}{{c}}{{$\\epsilon={float(e):.2f}$}}" for e in EPS)
sub = " & ".join(["calls & err.\\%"] * len(EPS))
cmid = "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(EPS)))
tex = ["\\begin{tabular}{@{}l" + "rr" * len(EPS) + "@{}}", "\\toprule", f"policy & {head} \\\\", cmid,
       f"& {sub} \\\\", "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
Path(__file__).with_name("maintenance.tex").write_text("% generated by paper/figs/maintenance.py\n" + "\n".join(tex) + "\n",
                                                        encoding="utf-8")
print("\n".join(tex))
