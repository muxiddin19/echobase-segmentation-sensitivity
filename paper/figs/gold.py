"""Tab. 4 (post-hoc, D5): per segmentation of the AMI eval meetings, the predicted shares and their distance to the
human dialogue-act labels (median over meetings), primary model.

    python paper/figs/gold.py    # reads reports/explore_gold_Qwen2.5-1.5B-Instruct.json -> paper/figs/gold.tex
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
g = json.loads((ROOT / "reports" / "explore_gold_Qwen2.5-1.5B-Instruct.json").read_text())["summary"]
LABEL = {"manual": "manual", "w1old": "diarizer (W1 old)", "w3old": "diarizer, est.\\ count", "placebo": "placebo",
         "merge2": "merge $k=2$", "merge4": "merge $k=4$", "merge8": "merge $k=8$"}
rows = []
for v, label in LABEL.items():
    q, a = g["question"].get(v), g["action_item"].get(v)
    if not q or not a:
        continue
    rows.append(f"{label} & {100 * q['share']:.1f} & {100 * q['abs_err']:.1f} & {q['f1']:.2f} & "
                f"{100 * a['share']:.1f} & {100 * a['abs_err']:.1f} & {a['f1']:.2f} \\\\")
tex = ["\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
       "& \\multicolumn{3}{c}{question} & \\multicolumn{3}{c}{action item (proxy)} \\\\",
       "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
       "segmentation & share & $|$err$|$ & F1 & share & $|$err$|$ & F1 \\\\", "\\midrule",
       f"human labels & {100 * g['question']['gold_share_median']:.1f} & & & {100 * g['action_item']['gold_share_median']:.1f} & & \\\\",
       "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
Path(__file__).with_name("gold.tex").write_text("% generated by paper/figs/gold.py\n" + "\n".join(tex) + "\n", encoding="utf-8")
print("\n".join(tex))
