"""Tab. cost: what measuring each workload costs with the primary model, next to its drift (held-out data).

    python paper/figs/cost.py     # reads reports/explore_cost.json, throughput.json, explore_eval.json,
                                  # explore_chunksize.json; writes paper/figs/cost.tex and reports/tables/cost.csv
Calls and prompt tokens cover both versions of a workload (old + new). GPU minutes on one TITAN Xp: AMI versions at
their measured rate (throughput.json); the two Wikipedia chunkers share one measured run, split by prompt tokens; the
100/150-word windows were scored on another host and are converted at that run's token rate (marked).
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REP = ROOT / "reports"
cost = json.loads((REP / "explore_cost.json").read_text())
thr = json.loads((REP / "throughput.json").read_text())
ev = json.loads((REP / "explore_eval.json").read_text())
ch = json.loads((REP / "explore_chunksize.json").read_text())

rate = {r["version"]: r["calls_per_s"] for r in thr if r["model"] == "Qwen2.5-1.5B"}
wiki = next(r for r in thr if r["version"] == "wiki-test")
wiki_sec = wiki["calls"] / wiki["calls_per_s"]
wiki_tok_rate = (cost["wiki/fixed"]["tokens"] + cost["wiki/para"]["tokens"]) / wiki_sec  # tokens per second


def minutes(v):
    if v in rate:
        return cost[v]["calls"] / rate[v] / 60, False
    return cost[v]["tokens"] / wiki_tok_rate / 60, v not in ("wiki/fixed", "wiki/para")


def drift(r):
    return r["median"], r["ci"]


ROWS = [("W1", "diarizer $\\to$ manual", ("w1old", "manual"), drift(ev["ami"]["W1"]["Q1"])),
        ("W2", "placebo", ("manual", "placebo"), drift(ev["ami"]["W2"]["Q1"])),
        ("W3", "est.\\ $\\to$ known count", ("w3old", "w1old"), drift(ev["ami"]["W3"]["Q1"])),
        *((f"E6", f"merge $k={k}$", ("manual", f"merge{k}"), drift(ev["ami"][f"E6_k{k}"]["Q1"])) for k in (2, 4, 8)),
        ("W4", "windows $\\to$ paragraphs", ("wiki/fixed", "wiki/para"), drift(ev["wiki"]["Qd1"])),
        ("", "window 120 $\\to$ 100", ("wiki/fixed", "wiki/fixed100"), drift(ch["120->100"])),
        ("", "window 120 $\\to$ 150", ("wiki/fixed", "wiki/fixed150"), drift(ch["120->150"]))]

lines, out = [], []
for wid, desc, vs, (med, ci) in ROWS:
    calls = sum(cost[v]["calls"] for v in vs)
    tok = sum(cost[v]["tokens"] for v in vs)
    mins = [minutes(v) for v in vs]
    gm, est = sum(m for m, _ in mins), any(e for _, e in mins)
    lines.append(f"{wid} & {desc} & {calls:,} & {tok / 1e6:.2f} & {gm:.0f}{'$^\\dagger$' if est else ''} & "
                 f"{med:.3f} [{ci[0]:.2f}, {ci[1]:.2f}] \\\\")
    out.append({"workload": wid, "change": desc, "calls": calls, "tokens": tok, "gpu_min": round(gm, 2),
                "gpu_min_estimated": est, "drift_median": med, "ci_lo": ci[0], "ci_hi": ci[1]})
    if desc.startswith("est"):
        lines.append("\\midrule")
    if wid == "E6" and desc.endswith("8$"):
        lines.append("\\midrule")

tex = ["% generated by paper/figs/cost.py", "\\begin{tabular}{@{}llrrrl@{}}", "\\toprule",
       "& change & calls & tok.\\ (M) & min & drift $D$ [95\\% CI] \\\\", "\\midrule", *lines, "\\bottomrule",
       "\\end{tabular}"]
(ROOT / "paper" / "figs" / "cost.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
(REP / "tables").mkdir(exist_ok=True)
with open(REP / "tables" / "cost.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(out[0]))
    w.writeheader()
    w.writerows(out)
print("\n".join(tex))
print(f"wiki run {wiki_sec:.0f} s, {wiki_tok_rate:.0f} tokens/s")
