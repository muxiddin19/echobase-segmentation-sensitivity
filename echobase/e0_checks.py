"""E0 checks 3-6 (plan v2) on dev data, computed from the cached outputs; writes reports/e0_checks_auto.md.

    python -m echobase.e0_checks
Change share (W3, W4): share of new segments whose change group (locked segmap.change_map) is not 'unchanged'
(W3: 3.1 estimated -> known speaker count; D3) or is split / merge / n:m (W4: fixed -> paragraph chunks). Headroom: Q(old) >= 0.02 per unit.
"""
from pathlib import Path

import numpy as np

from pilots.ami import meetings
from pilots.segmap import Segment, change_map

from .drift import AMI_QUERIES, GUARD, V2, ami_drift, ami_load, share, wiki_drift
from .lineage import system_version, versions
from .score_versions import W3_OLD

ROOT = Path(__file__).resolve().parents[1]
STRUCT = {"split", "merge", "n:m"}


def change_share(old_segs, new_segs, kinds=None):
    """(changed new segments, all new segments); kinds=None counts every kind except 'unchanged'."""
    changed = 0
    for k, _, n in change_map(old_segs, new_segs):
        if (k != "unchanged") if kinds is None else (k in kinds):
            changed += len(n)
    return changed, len(new_segs)


def wiki_segments(spans, tag):
    return [Segment(f"{tag}{i}", "doc", float(a), float(b), "") for i, (a, b) in enumerate(spans)]


def med(xs):
    xs = [x for x in xs if x is not None]
    return f"{np.median(xs):.3f} (n={len(xs)})" if xs else "n/a"


def main():
    import json
    from .wiki import articles
    L = ["# E0 checks 3-6 (dev only; generated by echobase/e0_checks.py)", ""]

    # E0.3 W2 placebo: manual -> placebo
    d = ami_drift("manual", "placebo")
    L += ["## E0.3 W2 placebo (manual -> placebo), median D per query", "",
          "| query | median D |", "|---|---|"] + [f"| {q} | {med(d[q].values())} |" for q in d] + [""]

    # E0.4 W3: pyannote 3.1 estimated -> known speaker count (same reference words; D3)
    done = [m for m in meetings("dev") if (W3_OLD / f"{m}.json").exists()]
    L += [f"## E0.4 W3 pyannote 3.1 estimated -> known speaker count ({len(done)} dev meetings; D3, exploratory)", ""]
    if done:
        L += ["| meeting | changed / new segments | share |", "|---|---|---|"]
        tot = [0, 0]
        for m in done:
            old = system_version(m, W3_OLD / f"{m}.json", "w3o")[0]
            new = versions(m)[0]
            c, n = change_share(old.segs, new.segs)
            tot[0] += c
            tot[1] += n
            L.append(f"| {m} | {c} / {n} | {c / n:.3f} |")
        L += [f"| pooled | {tot[0]} / {tot[1]} | **{tot[0] / tot[1]:.3f}** (rule >= 0.10) |", ""]
        if all((V2 / "w3old" / "action_item" / f"{m}.json").exists() for m in done):
            dw = ami_drift("w3old", "w1old", only=done)
            L += ["| query | median D (W3) |", "|---|---|"] + [f"| {q} | {med(dw[q].values())} |" for q in dw] + [""]
    else:
        L += ["no W3 old-side outputs yet", ""]

    # E0.5 W4 Wikipedia dev
    tot, units = [0, 0], []
    for art in articles("dev"):
        sp = {c: json.loads((V2 / "wiki" / c / "doc_date" / f"{art['id']}.json").read_text())["spans"]
              for c in ("fixed", "para")}
        c, n = change_share(wiki_segments(sp["fixed"], "f"), wiki_segments(sp["para"], "p"), STRUCT)
        tot[0] += c
        tot[1] += n
        units.append(c / n)
    w = wiki_drift("dev")
    valid = sum(v is not None for v in w["Qd1"].values())
    L += ["## E0.5 W4 Wikipedia dev (fixed 120 words -> paragraphs)", "",
          f"- split/merge/n:m share, pooled: **{tot[0] / tot[1]:.3f}** ({tot[0]} / {tot[1]} paragraph chunks; "
          f"per-article median {np.median(units):.3f}); rule >= 0.15",
          f"- Qd1(old) >= {GUARD}: **{valid} / {len(w['Qd1'])}** articles; rule >= 150",
          "", "| query | median D (W4) |", "|---|---|"] + [f"| {q} | {med(w[q].values())} |" for q in w] + [""]

    # E0.6 headroom: Q(old) >= 0.02 in >= 14 of 18 dev meetings, for the old side of W1 (w1old) and W2 (manual)
    L += ["## E0.6 headroom: meetings with Q(old) >= 0.02 (rule >= 14 of 18)", "",
          "| query | w1old (H1 old side) | manual (H2 old side) |", "|---|---|---|"]
    ms = meetings("dev")
    for q, (col, target) in AMI_QUERIES.items():
        cnt = [sum(share(*ami_load(v, col, m), target) >= GUARD for m in ms) for v in ("w1old", "manual")]
        L.append(f"| {q} {col}={target} | {cnt[0]} / {len(ms)} | {cnt[1]} / {len(ms)} |")
    out = "\n".join(L) + "\n"
    print(out)
    (ROOT / "reports" / "e0_checks_auto.md").write_text(out, encoding="utf-8")


if __name__ == "__main__":
    main()
