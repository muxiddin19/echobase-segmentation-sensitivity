"""Confirmatory analysis (PREREGISTRATION.md; plan v2.2 §8): H1 -> H2 -> H4 on AMI eval and Wikipedia test.

    python -m echobase.confirm            # after G1 and after E1-E3; writes reports/confirmatory.{json,md}
Run once. Refused before G1. Each test: median of unit drifts D, 95% CI by BCa over units (10,000 resamples, seed 0;
percentile interval if BCa is undefined). Verdict: supported (median >= T and CI low >= L); refuted (CI high < T);
inconclusive otherwise, or when fewer than the minimum valid units remain. Fixed sequence: a hypothesis is claimed
only if every earlier one is supported; all are computed and reported.
"""
import json
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

from pilots.ami import meetings

from .drift import V2, ami_drift, wiki_drift
from .gate import require_g1
from .power_sim import median_ci

ROOT = Path(__file__).resolve().parents[1]
N_RESAMPLES, SEED = 10_000, 0
AMI_COLS = ("action_item", "question", "entity_count", "sentiment", "topic")
DOC_COLS = ("doc_date", "doc_entity_count", "doc_topic")


def ami_units(old, new):
    """(available, all) eval meetings: available = every column cached for both versions (plan §8.8: a unit that
    failed twice has no cache and is removed)."""
    ms = meetings("eval")
    return [m for m in ms if all((V2 / v / c / f"{m}.json").exists() for v in (old, new) for c in AMI_COLS)], ms


def wiki_units(split="test"):
    from .wiki import articles
    ids = [a["id"] for a in articles(split)]
    return [i for i in ids if all((V2 / "wiki" / ch / c / f"{i}.json").exists()
                                  for ch in ("fixed", "para") for c in DOC_COLS)], ids


def ami(old, new):
    ok, ms = ami_units(old, new)
    return ami_drift(old, new, "eval", only=ok), ms


def wiki():
    ok, ids = wiki_units()
    return wiki_drift("test", only=set(ok)), ids


FAMILY = [  # id, statement, (loader -> ({query: {unit: D}}, all units), query), T, L, minimum valid units
    ("H1", "W1 diarizer -> manual, AMI eval", (lambda: ami("w1old", "manual"), "Q1"), 0.10, 0.05, 14),
    ("H2", "W2 placebo, AMI eval", (lambda: ami("manual", "placebo"), "Q1"), 0.05, 0.02, 14),
    ("H4", "W4 chunker, Wikipedia test", (lambda: wiki(), "Qd1"), 0.10, 0.05, 180),
]


def verdict(d, T, L, min_valid, rng, n_units=None):
    """d: {unit: D or None (excluded by the 0.02 guard)} over the available units; n_units: all planned units
    (missing ones count against min_valid). Returns the result record for one hypothesis."""
    x = np.array([v for v in d.values() if v is not None], dtype=float)
    n_units = len(d) if n_units is None else n_units
    rec = {"units": n_units, "missing": n_units - len(d), "excluded_guard": len(d) - len(x), "valid": len(x),
           "T": T, "L": L}
    if len(x) < min_valid:
        return dict(rec, verdict="inconclusive", reason=f"only {len(x)} valid units (< {min_valid})")
    low, high, how = median_ci(x, rng, N_RESAMPLES)
    above = int((x > T).sum())
    rec.update(median=float(np.median(x)), ci_low=float(low), ci_high=float(high), ci_method=how,
               sign_test_p=float(binomtest(above, int((x != T).sum()), 0.5, alternative="greater").pvalue))
    if rec["median"] >= T and low >= L:
        return dict(rec, verdict="supported")
    if high < T:
        return dict(rec, verdict="refuted")
    return dict(rec, verdict="inconclusive", reason="rule not met and CI upper >= T")


def run(family=FAMILY):
    out, chain = [], True
    for hid, what, (load, q), T, L, min_valid in family:
        drift, units = load()
        d = drift[q]
        r = verdict(d, T, L, min_valid, np.random.default_rng(SEED), len(units))
        r.update(id=hid, statement=what, query=q, claimed=chain and r["verdict"] == "supported",
                 missing_units=[u for u in units if u not in d], per_unit=dict(d))
        chain = r["claimed"]
        out.append(r)
    return out


def report(results):
    L = ["# Confirmatory results (generated by echobase/confirm.py; preregistered rules)", "",
         "| id | statement | valid / units (missing, guard-excluded) | median D | 95% CI | T / L | verdict | claimed (fixed sequence) | sign test p |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        ci = f"[{r['ci_low']:.3f}, {r['ci_high']:.3f}] ({r['ci_method']})" if "ci_low" in r else "-"
        med = f"{r['median']:.3f}" if "median" in r else "-"
        p = f"{r['sign_test_p']:.4f}" if "sign_test_p" in r else "-"
        L.append(f"| {r['id']} | {r['statement']} | {r['valid']} / {r['units']} ({r['missing']}, {r['excluded_guard']}) | {med} | {ci} | {r['T']} / {r['L']} | "
                 f"{r['verdict']}{' (' + r['reason'] + ')' if 'reason' in r else ''} | {'yes' if r['claimed'] else 'no'} | {p} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    require_g1("the confirmatory analysis")
    res = run()
    (ROOT / "reports" / "confirmatory.json").write_text(json.dumps(res, indent=1))
    (ROOT / "reports" / "confirmatory.md").write_text(report(res), encoding="utf-8")
    print(report(res))
